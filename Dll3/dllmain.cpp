		std::string aob1 = "4c 8d 0d ?? ?? ?? ?? 4c 8d 05 ?? ?? ?? ?? 8b 54 24 40 48 8b ?? e8 ?? ?? ?? ?? 48 8d ?? ?? ?? ?? ?? 48 ?? ?? ?? ?? ?? ?? c6 ?? ?? ?? ?? ?? ?? 48 ?? ?? ?? ?? ?? ?? ?? ?? ?? ?? c6 ?? ?? ?? ?? ?? ?? 4c ?? ?? ?? ?? ?? ?? 4c ?? ?? ?? ?? ?? ?? ?? ?? ?? ?? ?? ?? 48"; 
